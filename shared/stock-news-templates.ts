/** 이/가 after a Korean name (batchim check on the last syllable). */
export function subjectParticle(name: string): string {
  const code = name.charCodeAt(name.length - 1) - 0xAC00;
  return code >= 0 && code < 11172 && code % 28 !== 0 ? '이' : '가';
}
